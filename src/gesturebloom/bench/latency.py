"""Per-stage latency measurement.

Interactive systems are judged on latency, not throughput, and "60 fps" tells you
nothing about latency -- a pipeline can hold 60 fps while adding 100 ms of delay
through buffering. So the benchmark reports **per-stage percentiles**, and the
README table is generated by this module rather than typed by hand.

Two measurement decisions worth copying into other projects:

**p95, not mean.** Frame time distributions are right-skewed and it is the tail
that users feel. A pipeline with a 6 ms mean and a 40 ms p95 stutters visibly;
one with an 11 ms mean and a 13 ms p95 feels smooth. Reporting only the mean hides
exactly the thing that matters.

**Warm-up frames are discarded.** The first several frames include lazy library
init, JIT, shader compilation, and cold caches, and they can be 50x the steady
state. Including them makes your numbers meaningless in both directions.
"""

from __future__ import annotations

import time
from contextlib import contextmanager
from dataclasses import dataclass, field

import numpy as np

#: Canonical stage order for reporting.
STAGES = ("capture", "landmark", "canonical", "control", "inference", "geometry", "render")


@dataclass
class StageTimer:
    """Accumulates per-stage wall-clock samples in milliseconds.

    Examples
    --------
    >>> t = StageTimer(warmup=0)
    >>> with t.measure("control"):
    ...     _ = sum(range(1000))
    >>> t.frame_done()
    >>> len(t.samples["control"])
    1
    """

    warmup: int = 10
    samples: dict[str, list[float]] = field(default_factory=dict)
    frame_totals: list[float] = field(default_factory=list)
    _frames_seen: int = 0
    _current: dict[str, float] = field(default_factory=dict)

    @contextmanager
    def measure(self, stage: str):
        start = time.perf_counter()
        try:
            yield
        finally:
            elapsed_ms = (time.perf_counter() - start) * 1000.0
            self._current[stage] = self._current.get(stage, 0.0) + elapsed_ms

    def frame_done(self) -> None:
        """Close out the current frame, honouring the warm-up cutoff."""
        self._frames_seen += 1
        if self._frames_seen > self.warmup:
            for stage, ms in self._current.items():
                self.samples.setdefault(stage, []).append(ms)
            self.frame_totals.append(sum(self._current.values()))
        self._current = {}

    def stats(self, stage: str) -> dict[str, float]:
        arr = np.asarray(self.samples.get(stage, []), dtype=np.float64)
        if arr.size == 0:
            return {"mean": float("nan"), "p50": float("nan"), "p95": float("nan"), "n": 0}
        return {
            "mean": float(arr.mean()),
            "p50": float(np.percentile(arr, 50)),
            "p95": float(np.percentile(arr, 95)),
            "n": int(arr.size),
        }

    @property
    def achieved_fps(self) -> float:
        arr = np.asarray(self.frame_totals, dtype=np.float64)
        if arr.size == 0:
            return float("nan")
        return 1000.0 / float(np.percentile(arr, 50))

    def markdown_table(self, title: str = "") -> str:
        """Render a README-ready table. Paste the output; do not retype it."""
        lines = []
        if title:
            lines += [f"**{title}**", ""]
        lines += [
            "| Stage | mean (ms) | p50 (ms) | p95 (ms) |",
            "|---|---:|---:|---:|",
        ]
        ordered = [s for s in STAGES if s in self.samples]
        ordered += [s for s in self.samples if s not in STAGES]
        for stage in ordered:
            st = self.stats(stage)
            lines.append(f"| {stage} | {st['mean']:.2f} | {st['p50']:.2f} | {st['p95']:.2f} |")

        total = np.asarray(self.frame_totals, dtype=np.float64)
        if total.size:
            lines.append(
                f"| **end-to-end** | **{total.mean():.2f}** | "
                f"**{np.percentile(total, 50):.2f}** | **{np.percentile(total, 95):.2f}** |"
            )
            lines += ["", f"Achieved {self.achieved_fps:.1f} fps at the median frame time."]
        return "\n".join(lines)


def benchmark_pipeline(
    n_frames: int = 600,
    seed: int = 0,
    include_inference: bool = False,
) -> StageTimer:
    """Benchmark the camera-free stages against a synthetic landmark stream.

    Deliberately excludes capture and render by default, because those depend on
    hardware you cannot hold constant in CI. The value here is regression
    detection on the stages that are pure computation: if canonicalization
    suddenly costs 3x, this catches it.

    Examples
    --------
    >>> t = benchmark_pipeline(n_frames=60)
    >>> "canonical" in t.samples and "geometry" in t.samples
    True
    >>> t.stats("canonical")["n"] > 0
    True
    """
    from ..control.calibration import default_ranges
    from ..control.mapper import ControlMapper
    from ..data.recording import replay, synthetic_recording
    from ..geometry.spiderlily import build_spiderlily
    from ..landmarks.canonical import try_canonicalize
    from ..landmarks.filters import LandmarkSmoother
    from ..render.window import build_batch

    rec = synthetic_recording(n_frames=n_frames, seed=seed, dropout_rate=0.01)
    smoother = LandmarkSmoother(freq=rec.fps)
    mapper = ControlMapper(ranges=default_ranges(), freq=rec.fps)
    timer = StageTimer(warmup=min(20, n_frames // 4))

    model = None
    if include_inference:
        try:
            import torch

            from ..models.pose_mlp import PoseMLP, PoseMLPConfig

            model = PoseMLP(PoseMLPConfig(n_classes=8)).eval()
            _torch = torch
        except ImportError:
            model = None

    for lm, hand, dt in replay(rec):
        with timer.measure("landmark"):
            smoothed = smoother.update(lm, dt)
        if smoothed is None:
            timer.frame_done()
            continue

        with timer.measure("canonical"):
            res = try_canonicalize(smoothed, hand)
        if res is None:
            timer.frame_done()
            continue
        canonical, frame = res

        with timer.measure("control"):
            params = mapper.update(canonical, dt=dt, basis=frame.basis)

        if model is not None:
            with timer.measure("inference"):
                from ..landmarks.canonical import feature_vector

                x = _torch.from_numpy(feature_vector(canonical)).unsqueeze(0)
                with _torch.no_grad():
                    model(x)

        with timer.measure("geometry"):
            strands = build_spiderlily(params["grow"], params["bloom"], seed=0)
            build_batch(strands)

        timer.frame_done()

    return timer
